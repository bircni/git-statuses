#!/usr/bin/env bash
#
# Renders the Homebrew formula for a release to stdout. The release workflow commits the
# result to bircni/homebrew-tap as Formula/git-statuses.rb.
#
# Usage: scripts/homebrew_formula.sh <version> <directory holding the release archives>
#
# The version doubles as the tag name, which is how release_version.sh tags releases.

set -euo pipefail

# Function to print errors only
err() { echo "$@" 1>&2; }

if [ $# -ne 2 ]; then
    err "Usage: $0 <version> <archive directory>"
    exit 1
fi

version="$1"
archives="$2"
download="https://github.com/bircni/git-statuses/releases/download/${version}"

# Prints the SHA-256 of the archive built for the given target.
checksum() {
    local archive="${archives}/git-statuses-${version}-$1.tar.gz"
    if [ ! -f "$archive" ]; then
        err "Missing release archive: $archive"
        exit 1
    fi
    shasum -a 256 "$archive" | cut -d' ' -f1
}

# Resolved before rendering: a failure inside the heredoc would not stop the script.
sha_macos_arm=$(checksum aarch64-apple-darwin)
sha_macos_intel=$(checksum x86_64-apple-darwin)
sha_linux_intel=$(checksum x86_64-unknown-linux-musl)

cat <<EOF
# Generated by scripts/homebrew_formula.sh in bircni/git-statuses on every release.
# Changes made here are overwritten by the next release.
class GitStatuses < Formula
  desc "Display Git repository statuses in a table format"
  homepage "https://github.com/bircni/git-statuses"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  on_macos do
    on_arm do
      url "${download}/git-statuses-${version}-aarch64-apple-darwin.tar.gz"
      sha256 "${sha_macos_arm}"
    end
    on_intel do
      url "${download}/git-statuses-${version}-x86_64-apple-darwin.tar.gz"
      sha256 "${sha_macos_intel}"
    end
  end

  on_linux do
    # Only an x86_64 build is published for Linux.
    depends_on arch: :x86_64

    on_intel do
      url "${download}/git-statuses-${version}-x86_64-unknown-linux-musl.tar.gz"
      sha256 "${sha_linux_intel}"
    end
  end

  def install
    bin.install "git-statuses"
    generate_completions_from_executable(bin/"git-statuses", "--completions")
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/git-statuses --version")

    (testpath/"scan").mkpath
    assert_equal '{"failed":[],"repositories":[]}',
                 shell_output("#{bin}/git-statuses --json #{testpath}/scan").strip
  end
end
EOF
